/** Get all widget entries as an array */
export function getWidgetEntries(): WidgetRegistryEntry[] {
  return Object.values(widgetRegistry);
}

/** Get widget entries grouped by category */
export function getWidgetsByCategory(): Record<WidgetCategory, WidgetRegistryEntry[]> {
  const result: Record<WidgetCategory, WidgetRegistryEntry[]> = {
    overview: [],
    coverage: [],
    'threat-intel': [],
    quality: [],
    operations: [],
    mitre: [],
  };
  for (const entry of Object.values(widgetRegistry)) {
    result[entry.category].push(entry);
  }
  return result;
}

