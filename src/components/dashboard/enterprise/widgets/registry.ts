// ---------------------------------------------------------------------------
// Registry entry
// ---------------------------------------------------------------------------

export interface WidgetRegistryEntry {
  type: WidgetType;
  displayName: string;
  description: string;
  category: WidgetCategory;
  icon: string; // emoji or heroicon name
  /** React.lazy component */
  component: React.LazyExoticComponent<React.ComponentType<WidgetComponentProps>>;
  defaultConfig: Record<string, unknown>;
  /** Default grid size { w, h } in grid units */
  defaultSize: { w: number; h: number };
  /** Minimum grid size */
  minSize: { w: number; h: number };
  /** Optional maximum grid size */
  maxSize?: { w: number; h: number };
  /** Chart variants this widget supports */
  supportedChartVariants: ChartVariant[];
}

// ---------------------------------------------------------------------------
// Lazy imports
// ---------------------------------------------------------------------------

const lazy = (loader: () => Promise<{ default: React.ComponentType<WidgetComponentProps> }>) =>
  React.lazy(loader);

