-- E4c: give fetched rules the title they declare, instead of their filename.
--
-- E4's fix documents three steps, and step 3 reads: "Upgraded on fetch. Once
-- the file is in hand its own `title:` (Sigma/Sentinel) or `rule <name>`
-- (YARA) replaces the derived name." `deriveGitHubReferenceName` even carries
-- the comment "This is derived, not authoritative... deriveRuleTitleFromContent
-- supersedes it once the file has actually been fetched."
--
-- It never superseded anything. The extractor matched Sigma `title:` and YARA
-- `rule <name>`; every fetched rule in the corpus is Microsoft Sentinel, which
-- names the rule `name:`, or Elastic TOML, which uses `name = "..."`. Measured:
-- 7 fetched rules, 0 yielded a title, 7 carried one the function could not see.
-- A 0% hit rate, from the day it shipped.
--
-- The code fix landed first and was deployed before this ran -- the opposite
-- order is what produced E4b's six broken rows, where a backfill was overtaken
-- by the undeployed bug it had just corrected.
--
-- Names below were GENERATED by running the shipped, fixed
-- `deriveRuleTitleFromContent` over each rule's verbatim stored content. As an
-- independent check, the same titles were extracted separately with SQL
-- regexes; the two derivations agree on all 7. Re-running the module over the
-- updated rows yields the same values, so this is idempotent by construction.
--
-- Only `name` is written; every other key is merged through untouched.
--
-- Why the names change again after 20260811120000: that migration gave these
-- rules names derived from their FILENAME, which is all the shipped code could
-- produce at the time. This replaces them with the rule's own declared title,
-- which is what the pipeline was always documented to do.
--
--   NRT Office MailForwarding  ->  NRT Multiple users email forwarded to same destination
--
-- That row is not cosmetic. The library holds that exact detection under the
-- new name, twice (external_id 3b05727d-a8d1-477d-bbdd-d957da96ac7b) -- it is
-- E1's and G6's worked example. The filename-derived name matched nothing in
-- the library while the matching string sat unread inside the rule's own
-- fetched content.

CREATE TABLE IF NOT EXISTS _backup_rules_e4c_20260811 AS
SELECT id, rules, now() AS backed_up_at
FROM threat_intel_reports
WHERE EXISTS (
  SELECT 1 FROM jsonb_array_elements(rules) AS ru
  WHERE ru->>'sourceUrl' IS NOT NULL AND length(coalesce(ru->>'content','')) > 60
);

WITH fixes(rule_id, new_name) AS (VALUES
  ('rule_pattern_report_1778133924537_ulbbpbq_0', 'NTDLL Memory Protection Change via Unsigned DLL'),
  ('rule_pattern_report_1769008805053_jw9hrzy_1', 'Account MFA Modifications'),
  ('rule_pattern_report_1769008805053_jw9hrzy_2', 'Okta Fast Pass phishing Detection'),
  ('rule_pattern_report_1769008805053_jw9hrzy_6', 'SharePointFileOperation via clientIP with previously unseen user agents'),
  ('rule_pattern_report_1769008805053_jw9hrzy_7', 'SharePointFileOperation via devices with previously unseen user agents'),
  ('rule_pattern_report_1769008805053_jw9hrzy_24', 'NRT Multiple users email forwarded to same destination'),
  ('rule_pattern_73a1b2b9-576e-47da-a111-691e4e960c8e_0', 'Node.js Pre or Post-Install Script Execution')
)
UPDATE threat_intel_reports r
SET rules = (
  SELECT jsonb_agg(
    CASE WHEN f.rule_id IS NOT NULL
      THEN ru || jsonb_build_object('name', f.new_name)
      ELSE ru
    END
    ORDER BY ord   -- rule order is user-visible; preserve it
  )
  FROM jsonb_array_elements(r.rules) WITH ORDINALITY AS t(ru, ord)
  LEFT JOIN fixes f ON f.rule_id = ru->>'id'
)
WHERE EXISTS (
  SELECT 1 FROM jsonb_array_elements(r.rules) AS ru
  JOIN fixes f2 ON f2.rule_id = ru->>'id'
);

DO $$
DECLARE
  unnamed int;
  lost int;
  mutated int;
BEGIN
  -- Every fetched rule must now be named something other than its filename
  -- shape. Checked as: none of the seven still carries its pre-migration name.
  SELECT COUNT(*) INTO unnamed
  FROM threat_intel_reports, jsonb_array_elements(rules) AS ru
  WHERE ru->>'id' IN (
      'rule_pattern_report_1778133924537_ulbbpbq_0',
      'rule_pattern_report_1769008805053_jw9hrzy_1',
      'rule_pattern_report_1769008805053_jw9hrzy_2',
      'rule_pattern_report_1769008805053_jw9hrzy_6',
      'rule_pattern_report_1769008805053_jw9hrzy_7',
      'rule_pattern_report_1769008805053_jw9hrzy_24',
      'rule_pattern_73a1b2b9-576e-47da-a111-691e4e960c8e_0')
    AND ru->>'name' IN (
      'defense evasion ntdll memory protection change via unsigned dll',
      'AccountMFAModifications', 'PhishingDetection', 'sharepoint downloads',
      'SharePoint Downloads byNewUserAgent', 'NRT Office MailForwarding',
      'execution nodejs pre or post install script execution');
  IF unnamed > 0 THEN
    RAISE EXCEPTION 'E4c backfill incomplete: % rule(s) still carry the filename-derived name', unnamed;
  END IF;

  SELECT COUNT(*) INTO lost
  FROM _backup_rules_e4c_20260811 b
  JOIN threat_intel_reports r ON r.id = b.id
  WHERE jsonb_array_length(b.rules) <> jsonb_array_length(r.rules);
  IF lost > 0 THEN
    RAISE EXCEPTION 'E4c backfill changed rule counts on % report(s)', lost;
  END IF;

  -- Position-by-position: every key except `name` must be byte-identical.
  -- Content in particular -- the titles were read FROM it, so if it moved the
  -- names would be describing something other than what is stored.
  SELECT COUNT(*) INTO mutated
  FROM _backup_rules_e4c_20260811 b
  JOIN threat_intel_reports r ON r.id = b.id
  CROSS JOIN LATERAL (
    SELECT o.old_ru AS old_ru, n.new_ru AS new_ru
    FROM jsonb_array_elements(b.rules) WITH ORDINALITY AS o(old_ru, ord)
    JOIN jsonb_array_elements(r.rules) WITH ORDINALITY AS n(new_ru, ord2)
      ON n.ord2 = o.ord
  ) pair
  WHERE (pair.old_ru - 'name') <> (pair.new_ru - 'name');
  IF mutated > 0 THEN
    RAISE EXCEPTION 'E4c backfill changed fields it must not touch on % rule(s)', mutated;
  END IF;
END $$;
