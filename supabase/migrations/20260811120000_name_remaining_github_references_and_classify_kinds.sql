-- E4b/E3 catch-up: rules the Aug-7 backfills could not reach.
--
-- ROOT CAUSE, worth stating because it is not a code defect:
-- the Aug-7 migrations corrected the stored data, but the code that PRODUCES
-- that data was not deployed until 2026-08-11. For four days the auto-digest
-- kept writing rows in the old shape, behind the fix. Every rule with a null
-- `kind` was created on 2026-08-08 -- inside that window and nowhere else.
--
-- Two populations, one symptom each:
--
--   1. Twelve rules still named the constant 'GitHub Reference', in two groups
--      that the earlier migration missed for DIFFERENT reasons:
--
--      a) Six fetched references. 20260807110000 keyed on
--         `type = 'github_reference'`, but fetching OVERWRITES the type via
--         detectRuleType (to sigma / kql / other), so those rows were never in
--         its lookup. Keying on the type could not have worked; this migration
--         keys on the name, which is the thing that is actually wrong and which
--         a fetch cannot overwrite.
--
--      b) Six written on 2026-08-08 by the undeployed extractor. These store
--         the URL in `content` with `sourceUrl` null -- the shape the extractor
--         still produces at extraction time -- so the URL is read from
--         whichever field holds it.
--
--   2. Seven rules with no `kind` at all (neither query, reference, nor
--      description), from the same 2026-08-08 window across 2 reports.
--
-- The values below were GENERATED by running the shipped modules
-- (_shared/github-reference.ts deriveGitHubReferenceName / describeGitHubReference,
-- and _shared/rule-type.ts classifyRule) over the real stored rows, not by
-- reimplementing their logic in SQL. A second implementation is the drift this
-- codebase keeps being bitten by.
--
-- Names come from the URL, not from the fetched body: deriveRuleTitleFromContent
-- matches `title:` and YARA `rule <name>`, while these files use Sentinel
-- `name:` and TOML `name = "..."`. It therefore returns undefined for all of
-- them and the URL-derived name stands -- which is exactly what the shipped
-- fetch path does, so this backfill and the live code agree. (That the module
-- does not recognise Sentinel/TOML titles is a real gap, recorded separately;
-- it is deliberately NOT fixed here, because changing the naming rule inside a
-- backfill would make the two disagree again.)
--
-- Only `name`, `description` and `kind` are written. Content, type, sourceUrl
-- and every other key are merged through untouched.
--
-- Safe to re-run: rows already carrying the corrected values are rewritten with
-- the same values.

CREATE TABLE IF NOT EXISTS _backup_rules_e4b_20260811 AS
SELECT id, rules, now() AS backed_up_at
FROM threat_intel_reports
WHERE EXISTS (
  SELECT 1 FROM jsonb_array_elements(rules) AS ru
  WHERE ru->>'name' = 'GitHub Reference' OR ru->>'kind' IS NULL
);

WITH fixes(rule_id, new_name, new_description, new_kind) AS (VALUES
  -- (1b) Written 2026-08-08 by the undeployed extractor: URL lives in `content`,
  --      `sourceUrl` is null. Need both a name and a kind.
  ('rule_pattern_9812aec7-0f4e-4377-ac6f-c09dfaf4c248_0', 'execution mcp server child process', 'Detection rule reference from elastic/detection-rules', 'reference'),
  ('rule_pattern_9812aec7-0f4e-4377-ac6f-c09dfaf4c248_1', 'command and control unusual connection to suspicious top level domain', 'Detection rule reference from elastic/detection-rules', 'reference'),
  ('rule_pattern_9812aec7-0f4e-4377-ac6f-c09dfaf4c248_2', 'command and control unusual network connection to suspicious web service', 'Detection rule reference from elastic/detection-rules', 'reference'),
  ('rule_pattern_9812aec7-0f4e-4377-ac6f-c09dfaf4c248_3', 'discovery process discovery via builtin tools', 'Detection rule reference from elastic/detection-rules', 'reference'),
  ('rule_pattern_9812aec7-0f4e-4377-ac6f-c09dfaf4c248_4', 'persistence persistence via genai tool', 'Detection rule reference from elastic/protections-artifacts', 'reference'),
  ('rule_pattern_9812aec7-0f4e-4377-ac6f-c09dfaf4c248_5', 'execution suspicious python script execution and network connection', 'Detection rule reference from elastic/protections-artifacts', 'reference'),

  -- (1a) Fetched references whose type was overwritten, so the type-keyed
  --      migration never saw them. `kind` is already correct on these.
  ('rule_pattern_73a1b2b9-576e-47da-a111-691e4e960c8e_0', 'execution nodejs pre or post install script execution', 'Detection rule reference from elastic/detection-rules', NULL),
  ('rule_pattern_report_1769008805053_jw9hrzy_0', 'SuspiciousSignInFollowedByMFAModification', 'Detection rule reference from Azure/Azure-Sentinel', NULL),
  ('rule_pattern_report_1769008805053_jw9hrzy_1', 'AccountMFAModifications', 'Detection rule reference from Azure/Azure-Sentinel', NULL),
  ('rule_pattern_report_1769008805053_jw9hrzy_2', 'PhishingDetection', 'Detection rule reference from Azure/Azure-Sentinel', NULL),
  ('rule_pattern_report_1769008805053_jw9hrzy_6', 'sharepoint downloads', 'Detection rule reference from Azure/Azure-Sentinel', NULL),
  ('rule_pattern_report_1778133924537_ulbbpbq_0', 'defense evasion ntdll memory protection change via unsigned dll', 'Detection rule reference from elastic/protections-artifacts', NULL),

  -- (2) Correctly named already; only the kind is missing.
  --     classifyRule('CQL', content): type is an unrecognised query language,
  --     so it falls to the single-token shape test, and the content is a
  --     2,023-character multi-line query -- confirmed against the stored row.
  ('rule_ai_b81f002a-63fe-4891-b072-c198f7359101_0', NULL, NULL, 'query')
)
UPDATE threat_intel_reports r
SET rules = (
  SELECT jsonb_agg(
    CASE
      WHEN f.rule_id IS NOT NULL THEN
        -- strip_nulls so a NULL column means "leave this key alone" rather
        -- than writing a null over a correct value.
        ru || jsonb_strip_nulls(jsonb_build_object(
          'name', f.new_name,
          'description', f.new_description,
          'kind', f.new_kind
        ))
      ELSE ru
    END
    ORDER BY ord   -- rule order is user-visible; preserve it
  )
  FROM jsonb_array_elements(r.rules) WITH ORDINALITY AS t(ru, ord)
  LEFT JOIN fixes f ON f.rule_id = ru->>'id'
)
WHERE EXISTS (
  SELECT 1
  FROM jsonb_array_elements(r.rules) AS ru
  JOIN fixes f2 ON f2.rule_id = ru->>'id'
);

DO $$
DECLARE
  constant_names int;
  null_kinds int;
  lost int;
  mutated int;
BEGIN
  SELECT COUNT(*) INTO constant_names
  FROM threat_intel_reports, jsonb_array_elements(rules) AS ru
  WHERE ru->>'name' = 'GitHub Reference';
  IF constant_names > 0 THEN
    RAISE EXCEPTION 'E4b backfill incomplete: % rule(s) still named GitHub Reference', constant_names;
  END IF;

  SELECT COUNT(*) INTO null_kinds
  FROM threat_intel_reports, jsonb_array_elements(rules) AS ru
  WHERE ru->>'kind' IS NULL;
  IF null_kinds > 0 THEN
    RAISE EXCEPTION 'E4b backfill incomplete: % rule(s) still have no kind', null_kinds;
  END IF;

  SELECT COUNT(*) INTO lost
  FROM _backup_rules_e4b_20260811 b
  JOIN threat_intel_reports r ON r.id = b.id
  WHERE jsonb_array_length(b.rules) <> jsonb_array_length(r.rules);
  IF lost > 0 THEN
    RAISE EXCEPTION 'E4b backfill changed rule counts on % report(s)', lost;
  END IF;

  -- Position-by-position: every key except name/description/kind must be
  -- byte-identical to the snapshot, on every rule of every touched report.
  SELECT COUNT(*) INTO mutated
  FROM _backup_rules_e4b_20260811 b
  JOIN threat_intel_reports r ON r.id = b.id
  CROSS JOIN LATERAL (
    SELECT o.ord AS ord, o.old_ru AS old_ru, n.new_ru AS new_ru
    FROM jsonb_array_elements(b.rules) WITH ORDINALITY AS o(old_ru, ord)
    JOIN jsonb_array_elements(r.rules) WITH ORDINALITY AS n(new_ru, ord2)
      ON n.ord2 = o.ord
  ) pair
  WHERE (pair.old_ru - 'name' - 'description' - 'kind')
     <> (pair.new_ru - 'name' - 'description' - 'kind');
  IF mutated > 0 THEN
    RAISE EXCEPTION 'E4b backfill changed fields it must not touch on % rule(s)', mutated;
  END IF;
END $$;
