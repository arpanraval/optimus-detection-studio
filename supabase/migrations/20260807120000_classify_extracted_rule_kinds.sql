-- E3: give extracted rules a kind, and canonicalise their type spellings.
--
-- validateRuleCandidate stored whatever the model called a rule
-- (`String(value.query_type || 'other')`), never consulting the
-- ExtractedRuleType enum. 61 distinct values accumulated across 411 rules.
--
-- The count was not the real problem. The values were not all the same KIND
-- of thing: `kql` is a query language, `Palo Alto Networks Threat Prevention
-- Signature ID` (average content length: 5 characters) is an identifier for a
-- rule someone else holds, and `log analysis` is prose. Nothing in the record
-- distinguished them, so a Sigma rule and a 5-character vendor ID were both
-- "rules" with a "type".
--
-- Constraining the field to the 9-member enum was rejected: only about 30 of
-- the odd values are spelling variants, so the rest would have collapsed into
-- 'other', destroying the only record of what they were. The missing axis is
-- added instead.
--
-- The lookup below was GENERATED by the shipped module
-- (supabase/functions/_shared/rule-type.ts), so the backfill cannot disagree
-- with what the extractor will produce from now on. It keys on the type
-- string rather than the rule id: there are only 61 distinct types across 411
-- rules, so this stays a small table rather than a per-row dump.
--
-- Safe to re-run: rows already carrying the corrected values are rewritten
-- with the same values.

CREATE TABLE IF NOT EXISTS _backup_rules_e3_20260807 AS
SELECT id, rules, now() AS backed_up_at
FROM threat_intel_reports
WHERE jsonb_array_length(COALESCE(rules, '[]'::jsonb)) > 0;

