UPDATE threat_intel_reports r
SET rules = (
  SELECT jsonb_agg(
    CASE
      WHEN l.raw_type IS NOT NULL THEN
        -- Merge, so every other key on the rule survives untouched.
        ru || jsonb_build_object('type', l.new_type, 'kind', l.kind, 'typeRecognized', l.recognized)
      ELSE
        -- A type the lookup has never seen: leave the string alone, but still
        -- record that it was not recognised, rather than leaving the field
        -- absent and indistinguishable from "not yet classified".
        ru || jsonb_build_object('kind', 'query', 'typeRecognized', false)
    END
    ORDER BY ord   -- rule order is user-visible; preserve it
  )
  FROM jsonb_array_elements(r.rules) WITH ORDINALITY AS t(ru, ord)
  LEFT JOIN lookup l ON l.raw_type = ru->>'type'
)
WHERE jsonb_array_length(COALESCE(r.rules, '[]'::jsonb)) > 0;

DO $$
DECLARE
  unclassified int;
  lost int;
BEGIN
  SELECT COUNT(*) INTO unclassified
  FROM threat_intel_reports, jsonb_array_elements(rules) AS ru
  WHERE ru->>'kind' IS NULL;
  IF unclassified > 0 THEN
    RAISE EXCEPTION 'E3 backfill incomplete: % rule(s) still have no kind', unclassified;
  END IF;

  SELECT COUNT(*) INTO lost
  FROM _backup_rules_e3_20260807 b
  JOIN threat_intel_reports r ON r.id = b.id
  WHERE jsonb_array_length(b.rules) <> jsonb_array_length(r.rules);
  IF lost > 0 THEN
    RAISE EXCEPTION 'E3 backfill changed rule counts on % report(s)', lost;
  END IF;
END $$;
